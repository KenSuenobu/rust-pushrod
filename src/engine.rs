    /// Sets the run loop's event mask.
    ///
    /// Events whose class is not in the mask are dropped before routing and callbacks, and the
    /// backend is told the mask so it can stop delivering the rest.  Close requests are always delivered.  The change applies from the next event
    /// and emits [`EngineEvent::EventMaskChanged`] with [`MaskScope::RunLoop`].
    ///
    /// With [`EventMask::TIMER`] left out and nothing to repaint, the loop blocks waiting for
    /// input instead of polling, so an idle application uses almost no CPU.
    ///
    /// # Arguments
    ///
    /// * `mask` - The classes of events to handle.  The default is [`EventMask::ALL`].
    ///
    /// # Examples
    ///
    /// ```rust
    /// use pushrod::engine::Engine;
    /// use pushrod::event::EventMask;
    /// use pushrod::geometry::size;
    ///
    /// let mut engine: Engine = Engine::new(size(320, 200), 60);
    ///
    /// // No hover effects: stop pointer motion at the source.
    /// engine.set_event_mask(EventMask::ALL & !EventMask::POINTER_MOTION & !EventMask::HOVER);
    ///
    /// assert!(!engine.event_mask().contains(EventMask::HOVER));
    /// ```
    pub fn set_event_mask(&mut self, mask: EventMask) {
        set_loop_mask(&mut self.event_mask, &mut self.widget_cache, mask);
    }

    /// Starts or stops publishing the accessibility tree.
    ///
    /// Backends call this (through [`InputEvent::AccessibilityActivated`]) when a screen reader
    /// connects or leaves.  While inactive, the `Engine` builds no tree and pays nothing.  The
    /// first [`Engine::accessibility_update`] after activation holds the whole tree.  A change
    /// queues [`EngineEvent::AccessibilityChanged`].
    ///
    /// # Arguments
    ///
    /// * `active` - `true` when assistive technology needs the tree.
    pub fn set_accessibility_active(&mut self, active: bool) {
        if active == self.accessibility.is_some() {
            return;
        }

        self.accessibility = active.then(AccessTree::new);
        self.widget_cache
            .queue_event(Event::Engine(EngineEvent::AccessibilityChanged { active }));
    }

    /// Returns whether the accessibility tree is being published.
    ///
    /// # Returns
    ///
    /// `true` while assistive technology is active.
    pub fn is_accessibility_active(&self) -> bool {
        self.accessibility.is_some()
    }

    /// Returns what changed in the accessibility tree since the last call.
    ///
    /// # Returns
    ///
    /// The changed nodes (all of them the first time), or `None` if assistive technology is not
    /// active or nothing changed.
    pub fn accessibility_update(&mut self) -> Option<AccessUpdate> {
        self.accessibility.as_mut()?.update(&self.widget_cache)
    }

    /// Performs a request from assistive technology, calling the same callbacks that user input
    /// calls.  See [`WidgetCache::perform_access_action`].
    ///
    /// # Arguments
    ///
    /// * `id` - The `Widget` the request is for.
    /// * `action` - What it is asked to do.
    /// * `state` - The application state passed to the callbacks.
    ///
    /// # Returns
    ///
    /// `true` if the action was performed; `false` if the `Widget` refused it.
    pub fn perform_access_action(
        &mut self,
        id: WidgetId,
        action: AccessAction,
        state: &mut S,
    ) -> bool {
        self.custom_budget = MAX_CUSTOM_EVENTS_PER_FRAME;

        let Some(events) = self.widget_cache.perform_access_action(id, &action) else {
            return false;
        };

        for event in self.expand_custom(events) {
            self.fire(&event, state);
        }

        self.flush_pending(state);

        true
    }

    /// Returns the run loop's event mask.
    ///
    /// # Returns
    ///
    /// The mask set with [`Engine::set_event_mask`]; [`EventMask::ALL`] by default.
    pub fn event_mask(&self) -> EventMask {
        self.event_mask
    }

    /// Returns whether the run loop can block waiting for input: nothing needs repainting, timer
    /// events are masked out, and no idle callbacks want to run.
    fn is_idle(&self) -> bool {
        !self.event_mask.intersects(EventMask::TIMER)
            && !self.widget_cache.needs_draw()
            && self.idle_callbacks.is_empty()
    }

    /// Returns how long an idle loop may block waiting for input: [`IDLE_WAIT_MS`], or less when
    /// a timer is due sooner, so timers still fire on time while the loop sleeps.
    ///
    /// # Arguments
    ///
    /// * `now` - The current time.
    ///
    /// # Returns
    ///
    /// The wait in milliseconds.
    fn idle_wait_ms(&self, now: Instant) -> u32 {
        match self.timers.next_wait(now) {
            Some(wait) => (wait.as_micros().div_ceil(1000) as u32).min(IDLE_WAIT_MS),
            None => IDLE_WAIT_MS,
        }
    }

    /// Starts a timer.
    ///
    /// The callback runs from the run loop (or [`Engine::next_event_with`]) once `interval` has
    /// passed, within one frame of it.  A repeating timer runs again every `interval`; if the
    /// application falls behind it runs once and keeps its rhythm instead of catching up in a
    /// burst.  Each firing emits [`EngineEvent::TimerFired`].  The callback receives the
    /// application state and a [`Ui`]; call [`Ui::cancel_timer`] to stop a timer, even from its
    /// own callback.
    ///
    /// # Arguments
    ///
    /// * `interval` - The time until the timer fires, and between firings if it repeats.
    /// * `repeat` - `true` to fire every `interval`; `false` to fire once.
    /// * `callback` - Runs each time the timer fires.
    ///
    /// # Returns
    ///
    /// The timer's [`TimerId`], for cancelling it.
    ///
    /// # Examples
    ///
    /// ```rust
    /// use pushrod::engine::Engine;
    /// use pushrod::geometry::size;
    /// use std::time::Duration;
    ///
    /// let mut engine: Engine<u32> = Engine::new(size(320, 200), 60);
    ///
    /// // Counts seconds; the application reads the count from its state.
    /// let clock = engine.on_timer(Duration::from_secs(1), true, |seconds, _ui| *seconds += 1);
    ///
    /// assert!(engine.cancel_timer(clock));
    /// ```
    pub fn on_timer<F>(&mut self, interval: Duration, repeat: bool, callback: F) -> TimerId
    where
        F: FnMut(&mut S, &mut Ui<S>) + 'static,
    {
        let id = self.timers.add(Instant::now(), interval, repeat);

        self.timer_callbacks.insert(id, Box::new(callback));

        id
    }

    /// Cancels a timer started with [`Engine::on_timer`].  Emits [`EngineEvent::TimerCancelled`]
    /// when a waiting timer was stopped.
    ///
    /// # Arguments
    ///
    /// * `id` - The timer to cancel.
    ///
    /// # Returns
    ///
    /// `true` if the timer was still scheduled.
    pub fn cancel_timer(&mut self, id: TimerId) -> bool {
        let cancelled = self.timers.cancel(id);

        if cancelled {
            self.timer_callbacks.remove(&id);
            self.widget_cache
                .queue_event(Event::Engine(EngineEvent::TimerCancelled { id }));
        }

        cancelled
    }

    /// Registers a callback that runs when the loop is idle: once per loop iteration in which no
    /// events were waiting.  Use it for work that should yield to input, such as deferred layout
    /// or incremental loading.  While any idle callback is registered the loop polls once per
    /// frame instead of blocking, so keep the callback short.  Each run emits
    /// [`EngineEvent::IdleRan`].
    ///
    /// # Arguments
    ///
    /// * `callback` - Receives the application state and a [`Ui`].
    ///
    /// # Examples
    ///
    /// ```rust
    /// use pushrod::engine::Engine;
    /// use pushrod::geometry::size;
    ///
    /// let mut engine: Engine<Vec<u32>> = Engine::new(size(320, 200), 60);
    ///
    /// // Loads one item per idle iteration.
    /// engine.on_idle(|loaded, _ui| loaded.push(loaded.len() as u32));
    /// ```
    pub fn on_idle<F>(&mut self, callback: F)
    where
        F: FnMut(&mut S, &mut Ui<S>) + 'static,
    {
        self.idle_callbacks.push(Box::new(callback));
    }

    /// Runs the timers that are due at `now`, in due order.  Events they cause are queued, not
    /// delivered.
    ///
    /// # Arguments
    ///
    /// * `now` - The current time.
    /// * `state` - The application state passed to the callbacks.
    fn run_due_timers(&mut self, now: Instant, state: &mut S) {
        for id in self.timers.due(now) {
            // Skip a timer an earlier callback cancelled in this same pass.
            let Some(repeat) = self.timers.complete(id, now) else {
                continue;
            };

            self.widget_cache
                .queue_event(Event::Engine(EngineEvent::TimerFired { id, repeat }));

            let Some(mut callback) = self.timer_callbacks.remove(&id) else {
                continue;
            };
            let mut ui = Ui {
                widgets: &mut self.widget_cache,
                running: &mut self.running,
                event_mask: &mut self.event_mask,
                posted: &mut self.posted,
                timers: &mut self.timers,
                modals: &mut self.modal_callbacks,
                resources: &self.resources,
                actions: &mut self.actions,
            };

            callback(state, &mut ui);

            if repeat && self.timers.contains(id) {
                self.timer_callbacks.insert(id, callback);
            }
        }

        let timers = &self.timers;

        self.timer_callbacks.retain(|id, _| timers.contains(*id));
    }

    /// Runs the idle callbacks, if there are any.  Queues [`EngineEvent::IdleRan`].
    ///
    /// # Arguments
    ///
    /// * `state` - The application state passed to the callbacks.
    fn run_idle_callbacks(&mut self, state: &mut S) {
        if self.idle_callbacks.is_empty() {
            return;
        }

        let mut ui = Ui {
            widgets: &mut self.widget_cache,
            running: &mut self.running,
            event_mask: &mut self.event_mask,
            posted: &mut self.posted,
            timers: &mut self.timers,
            modals: &mut self.modal_callbacks,
            resources: &self.resources,
            actions: &mut self.actions,
        };

        for callback in self.idle_callbacks.iter_mut() {
            callback(state, &mut ui);
        }

        let callbacks = self.idle_callbacks.len();

        self.widget_cache
            .queue_event(Event::Engine(EngineEvent::IdleRan { callbacks }));
    }

    /// Delivers [`Event::Tick`] to the `Widget`s that requested animation, measuring the time
    /// since the previous call.
    ///
    /// # Arguments
    ///
    /// * `now` - The current time.
    ///
    /// # Returns
    ///
    /// The events the `Widget`s generated while handling the tick.
    fn tick_widgets(&mut self, now: Instant) -> Vec<Event> {
        let elapsed = now.saturating_duration_since(self.last_tick);

        self.last_tick = now;

        let generated = self.widget_cache.tick(elapsed);

        self.expand_custom(generated)
    }

    /// Advances the engine's clock to `now`: runs the timers that are due, then delivers one
    /// [`Event::Tick`] to the `Widget`s that requested animation, and delivers everything they
    /// cause to the callbacks.  [`Engine::run`] calls this once per frame; call it directly to
    /// test an application's timers headless, with times of your own choosing.
    ///
    /// # Arguments
    ///
    /// * `now` - The current time.
    /// * `state` - The application state passed to the callbacks.
    pub fn advance(&mut self, now: Instant, state: &mut S) {
        self.custom_budget = MAX_CUSTOM_EVENTS_PER_FRAME;
        self.run_due_timers(now, state);

        for event in self.tick_widgets(now) {
            self.fire(&event, state);
        }

        self.flush_pending(state);
    }

    /// Runs the idle callbacks and delivers the events they cause.  [`Engine::run`] calls this
    /// when a frame had no events to process; call it directly to test idle callbacks headless.
    ///
    /// # Arguments
    ///
    /// * `state` - The application state passed to the callbacks.
    pub fn run_idle(&mut self, state: &mut S) {
        self.custom_budget = MAX_CUSTOM_EVENTS_PER_FRAME;
        self.run_idle_callbacks(state);
        self.flush_pending(state);
    }

    /// Takes the engine events queued by internal actions and broadcasts each to the `Widget`s
    /// that want it.
    ///
    /// # Returns
    ///
    /// Each engine event followed by the events the `Widget`s generated in response, in order.
    fn drain_pending(&mut self) -> Vec<Event> {
        self.sync_text_input();

        let mut drained = Vec::new();
        let mut posted = std::mem::take(&mut self.posted);

        if let Ok(mut queue) = self.mailbox.queue.lock() {
            posted.extend(queue.drain(..).map(|(target, payload)| {
                let payload: Rc<dyn Any + Send> = Rc::from(payload);

                Event::Custom(CustomEvent {
                    source: None,
                    target,
                    payload,
                })
            }));
        }

        drained.extend(self.expand_custom(posted));

        for event in self.widget_cache.take_pending_events() {
            let generated = match &event {
                Event::Engine(engine_event) => {
                    self.widget_cache.broadcast_engine_event(engine_event)
                }
                _ => Vec::new(),
            };

            drained.push(event);
            drained.extend(self.expand_custom(generated));
        }

        drained
    }

    /// Notes when text input should start or stop to match the focused `Widget`: on while a text
    /// editor has focus, off otherwise.  The run loop applies the change to the backend.
    fn sync_text_input(&mut self) {
        let wanted = self.widget_cache.text_input_wanted();

        if wanted != self.text_input_active {
            self.text_input_active = wanted;
            self.text_input_pending = Some(wanted);
        }
    }

    /// Passes changes made since the last call on to the backend: the event mask, text input, and
    /// the clipboard.
    ///
    /// # Arguments
    ///
    /// * `backend` - The backend to update.
    /// * `applied` - The mask the backend is configured for; updated to the current mask.
    fn sync_backend(&mut self, backend: &mut dyn Backend, applied: &mut EventMask) {
        if *applied != self.event_mask {
            backend.set_event_mask(self.event_mask);
            *applied = self.event_mask;
        }

        if let Some(active) = self.text_input_pending.take() {
            backend.set_text_input(active);
        }

        // Text copied by a widget goes to the system clipboard; while a text editor has the
        // focus, its paste sees the system clipboard as of this pass.
        if let Some(text) = self.widget_cache.take_clipboard_write() {
            backend.set_clipboard_text(&text);
        }

        if self.widget_cache.text_input_wanted() {
            self.widget_cache
                .set_clipboard_snapshot(backend.clipboard_text());
        }
    }

    /// Gives the backend the focused text editor's caret rectangle when it moved, so the
    /// platform's candidate window follows it.  Run after painting, since a field scrolls its
    /// text while it paints.
    ///
    /// # Arguments
    ///
    /// * `backend` - The backend to update.
    fn sync_text_input_rect(&mut self, backend: &mut dyn Backend) {
        let rect = self.widget_cache.focused_text_input_rect();

        if rect != self.text_input_rect {
            if let Some(rect) = rect {
                backend.set_text_input_rect(rect);
            }

            self.text_input_rect = rect;
        }
    }

    /// Delivers every custom event in `events` to its target `Widget`s, in order.
    ///
    /// Each event from a composite's part is followed by the events the composite translated it
    /// into ([`Composite::handle_part_event`](crate::composite::Composite::handle_part_event)).
    /// Each custom event is followed in the result by nothing of its own; the events the `Widget`s
    /// generate while handling it join the back of the queue, so custom events posted during
    /// delivery are delivered after the ones already waiting.  Once the frame's budget of
    /// [`MAX_CUSTOM_EVENTS_PER_FRAME`] is spent, further custom events are dropped and an
    /// [`EngineEvent::CustomEventDropped`] is returned in place of each.
    ///
    /// # Arguments
    ///
    /// * `events` - The events to expand; other kinds pass through unchanged.
    ///
    /// # Returns
    ///
    /// The events to give the callbacks, in delivery order.
    fn expand_custom(&mut self, events: Vec<Event>) -> Vec<Event> {
        let mut out = Vec::with_capacity(events.len());
        let mut queue: VecDeque<Event> = events.into();

        while let Some(event) = queue.pop_front() {
            let Event::Custom(custom) = &event else {
                // A composite sees its parts' events right after them; its own custom events
                // wait their turn like any other.
                let translated = self.widget_cache.translate_part_event(&event);

                out.push(event);

                for generated in translated {
                    if matches!(generated, Event::Custom(_)) {
                        queue.push_back(generated);
                    } else {
                        out.push(generated);
                    }
                }

                continue;
            };

            if self.custom_budget == 0 {
                out.push(Event::Engine(EngineEvent::CustomEventDropped {
                    target: custom.target,
                }));
                continue;
            }

            self.custom_budget -= 1;
            queue.extend(self.widget_cache.deliver_custom(custom));
            out.push(event);
        }

        out
    }

    /// Delivers the engine events queued by internal actions to the `Widget`s and callbacks.
    fn flush_pending(&mut self, state: &mut S) {
        loop {
            let pending = self.drain_pending();

            if pending.is_empty() {
                break;
            }

            for event in pending {
                self.fire(&event, state);
            }
        }
    }


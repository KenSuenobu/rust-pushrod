//! # Engine
//!
//! This is the run loop processor that enables `Pushrod` to open a new window, layout the `Widget`s
//! in the display, and handle the `Event` loop.
//!
//! The event loop processes events in order of receipt from the `SDL2` library, which uses the
//! `event_pump` function to get a list of events to process.  The events are sent to the
//! `WidgetCache`, which routes them to the `Widget`s.  Any `Event`s generated by the
//! `Widget`s are queued, and then delivered to the callbacks registered on the `Engine`.
//!
//! The `Engine` owns an application state object of any type `S`.  Callbacks receive mutable
//! access to that state, and to the `Widget`s through a [`Ui`] handle, in the style of Visual
//! Basic event procedures:
//!
//! The example uses the standard widgets from the `pushrod-widgets` crate; the core itself
//! contains no widgets other than the window's [`RootWidget`].
//!
//! ```rust,ignore
//! use pushrod::engine::Engine;
//! use pushrod::geometry::{point, size};
//! use pushrod_widgets::button_widget::ButtonWidget;
//! use pushrod_widgets::text_widget::{TextJustify, TextWidget};
//! use pushrod::color::{Color, FontStyle};
//!
//! #[derive(Default)]
//! struct AppState {
//!     clicks: u32,
//! }
//!
//! let sdl = sdl2::init().unwrap();
//! let window = sdl.video().unwrap().window("app", 400, 200).build().unwrap();
//! let mut engine: Engine<AppState> = Engine::new(size(400, 200), 30);
//!
//! let font = String::from("assets/OpenSans-Regular.ttf");
//! let label = engine.add_widget(TextWidget::new(point(20, 20), size(200, 20), font.clone(),
//!     FontStyle::NORMAL, 14, Color::BLACK, TextJustify::Left, String::from("Not clicked")));
//! let button = engine.add_widget(ButtonWidget::new(point(20, 60), size(120, 20), font,
//!     FontStyle::NORMAL, 14, Color::BLACK, TextJustify::Center, String::from("Click me"), 2));
//!
//! engine.on_click(button, move |state, ui| {
//!     state.clicks += 1;
//!     ui.get_mut::<TextWidget>(label)
//!         .unwrap()
//!         .set_text(format!("Clicked {} times", state.clicks));
//! });
//!
//! engine.run(sdl, window, AppState::default());
//! ```

use crate::cache::WidgetCache;
use crate::color::Color;
use crate::event::Event;
use crate::font::FontCache;
use crate::geometry::Size;
use crate::root_widget::RootWidget;
use crate::widget::{Widget, WidgetId};
use sdl2::event::{Event as SdlEvent, WindowEvent};
use sdl2::pixels::Color as SdlColor;
use sdl2::render::Canvas;
use sdl2::video::Window;
use sdl2::{EventPump, Sdl};
use std::collections::{HashMap, VecDeque};
use std::thread::sleep;
use std::time::{Duration, Instant};

/// A callback that runs when a particular `Widget` is clicked.
///
/// It receives the application state and a [`Ui`] handle for reaching the `Widget`s.  Register one
/// with [`Engine::on_click`].
pub type ClickCallback<S> = Box<dyn FnMut(&mut S, &mut Ui)>;

/// A callback that receives every event the `Widget`s generate.
///
/// It receives the application state, a [`Ui`] handle for reaching the `Widget`s, and the event.
/// Register one with [`Engine::on_event`].
pub type EventCallback<S> = Box<dyn FnMut(&mut S, &mut Ui, &Event)>;

/// The handle passed to callbacks.
///
/// It gives callbacks access to the `Widget`s in the window, by ID and concrete type, and lets
/// them stop the `Engine`.  It borrows the `Engine`'s widget tree only for the duration of the
/// callback.
pub struct Ui<'a> {
    widgets: &'a mut WidgetCache,
    running: &'a mut bool,
}

impl<'a> Ui<'a> {
    /// Retrieves a `Widget` by ID as its concrete type.
    ///
    /// # Arguments
    ///
    /// * `id` - The ID of the `Widget`.
    ///
    /// # Returns
    ///
    /// The `Widget` as a `T`, or `None` if the ID does not exist or the `Widget` is not a `T`.
    pub fn get<T: Widget>(&self, id: WidgetId) -> Option<&T> {
        self.widgets.get_as::<T>(id)
    }

    /// Retrieves a `Widget` by ID as its concrete type, for modification.
    ///
    /// # Arguments
    ///
    /// * `id` - The ID of the `Widget`.
    ///
    /// # Returns
    ///
    /// The `Widget` as a mutable `T`, or `None` if the ID does not exist or the `Widget` is not a `T`.
    pub fn get_mut<T: Widget>(&mut self, id: WidgetId) -> Option<&mut T> {
        self.widgets.get_as_mut::<T>(id)
    }

    /// Returns the window's widget tree.
    ///
    /// Use it to add `Widget`s from a callback, or to reach a `Widget` without knowing its concrete
    /// type.
    ///
    /// # Returns
    ///
    /// The [`WidgetCache`] holding every `Widget` in the window.
    pub fn widgets(&mut self) -> &mut WidgetCache {
        self.widgets
    }

    /// Stops the `Engine`.
    ///
    /// The run loop finishes the current batch of events, then returns the application state from
    /// [`Engine::run`]; in the event-loop style, [`Engine::next_event`] returns `None`.
    pub fn shutdown(&mut self) {
        *self.running = false;
    }
}

/// The run loop: owns the window's widget tree, routes input to `Widget`s, calls the application's
/// callbacks, and draws.
///
/// `S` is the application state type.  [`Engine::run`] takes ownership of a value of `S`, passes
/// it to every callback, and returns it when the `Engine` stops.  Applications that prefer their
/// own loop use [`Engine::event_loop`] and [`Engine::next_event`] instead of callbacks.
pub struct Engine<S = ()> {
    frame_rate: u32,
    size: Size,
    running: bool,
    widget_cache: WidgetCache,
    font_cache: FontCache,
    click_callbacks: HashMap<WidgetId, Vec<ClickCallback<S>>>,
    event_callbacks: Vec<EventCallback<S>>,
}

impl<S> Engine<S> {
    /// Creates an `Engine` for a window of the given size.
    ///
    /// A white [`RootWidget`] is created as `Widget` `0` and fills the window.
    ///
    /// # Arguments
    ///
    /// * `size` - The size of the window in pixels.
    /// * `frame_rate` - The maximum number of frames drawn per second (for example `30` or `60`).
    ///   `0` is treated as `1`.
    ///
    /// # Returns
    ///
    /// A new `Engine` with no `Widget`s other than the root, and no callbacks.
    pub fn new(size: Size, frame_rate: u32) -> Self {
        let mut widget_cache = WidgetCache::default();
        widget_cache.add(Box::new(RootWidget::new(Size::new(size.w, size.h))));

        Self {
            frame_rate,
            size,
            running: true,
            widget_cache,
            font_cache: FontCache::default(),
            click_callbacks: HashMap::new(),
            event_callbacks: Vec::new(),
        }
    }

    /// Stops the `Engine`.
    ///
    /// The run loop exits after the current batch of events; in the event-loop style,
    /// [`Engine::next_event`] returns `None`.
    pub fn shutdown(&mut self) {
        self.running = false;
    }

    /// Returns whether the `Engine` is running.
    ///
    /// # Returns
    ///
    /// `true` until the window is closed or [`shutdown`](Engine::shutdown) is called.
    pub fn is_running(&self) -> bool {
        self.running
    }

    /// Adds a `Widget` to the window, as a child of the root `Widget`.
    ///
    /// # Arguments
    ///
    /// * `widget` - The `Widget` to add.  Its origin is relative to the window.
    ///
    /// # Returns
    ///
    /// The ID assigned to the `Widget`; use it to register callbacks and to reach the `Widget` later.
    pub fn add_widget<W: Widget>(&mut self, widget: W) -> WidgetId {
        self.widget_cache.add(Box::new(widget))
    }

    /// Adds a `Widget` as a child of another `Widget`.
    ///
    /// Children move with their parent, are hidden with it, and are drawn on top of it.
    ///
    /// # Arguments
    ///
    /// * `parent` - The ID of the parent `Widget`.
    /// * `widget` - The `Widget` to add.  Its origin is relative to the parent.
    ///
    /// # Returns
    ///
    /// The ID assigned to the `Widget`.
    ///
    /// # Panics
    ///
    /// Panics if `parent` does not exist.
    pub fn add_child_widget<W: Widget>(&mut self, parent: WidgetId, widget: W) -> WidgetId {
        self.widget_cache.add_child(parent, Box::new(widget))
    }

    /// Returns the window's widget tree.
    ///
    /// # Returns
    ///
    /// The [`WidgetCache`] holding every `Widget` in the window.
    pub fn widgets(&mut self) -> &mut WidgetCache {
        &mut self.widget_cache
    }

    /// Registers a callback that runs when a `Widget` is clicked.
    ///
    /// Several callbacks may be registered for the same `Widget`; they run in the order registered,
    /// before any [`on_event`](Engine::on_event) callbacks.  Callbacks only run with
    /// [`Engine::run`] and [`Engine::dispatch`], not in the event-loop style.
    ///
    /// # Arguments
    ///
    /// * `id` - The ID of the `Widget`.
    /// * `callback` - Called with the application state and a [`Ui`] handle.
    ///
    /// # Examples
    ///
    /// ```rust
    /// use pushrod::engine::Engine;
    /// use pushrod::geometry::size;
    ///
    /// let mut engine: Engine<u32> = Engine::new(size(320, 200), 30);
    ///
    /// engine.on_click(0, |clicks, _ui| *clicks += 1);
    /// ```
    pub fn on_click<F>(&mut self, id: WidgetId, callback: F)
    where
        F: FnMut(&mut S, &mut Ui) + 'static,
    {
        self.click_callbacks
            .entry(id)
            .or_default()
            .push(Box::new(callback));
    }

    /// Registers a callback that receives every event the `Widget`s generate.
    ///
    /// These callbacks run after the `Widget`-specific callbacks for the same event, in the order
    /// registered.
    ///
    /// # Arguments
    ///
    /// * `callback` - Called with the application state, a [`Ui`] handle, and the event.
    pub fn on_event<F>(&mut self, callback: F)
    where
        F: FnMut(&mut S, &mut Ui, &Event) + 'static,
    {
        self.event_callbacks.push(Box::new(callback));
    }

    /// Sets the window's background color.
    ///
    /// This is the color of the [`RootWidget`] (ID `0`), which fills the window behind every other
    /// `Widget`.
    ///
    /// # Arguments
    ///
    /// * `color` - The new background color.
    pub fn set_background(&mut self, color: Color) {
        if let Some(root) = self.widget_cache.get_mut(crate::widget::ROOT_WIDGET_ID) {
            root.set_color(color);
        }
    }

    /// Returns the size of the window.
    ///
    /// # Returns
    ///
    /// The window size given to [`Engine::new`].
    pub fn get_size(&self) -> Size {
        self.size
    }

    /// Processes one raw input event, as the run loop does.
    ///
    /// The event is routed to the `Widget`s, and every event they generate is delivered to the
    /// registered callbacks, in order.  Useful for testing an application without opening a window.
    ///
    /// # Arguments
    ///
    /// * `event` - The raw `SDL2` event.
    /// * `state` - The application state passed to the callbacks.
    pub fn dispatch(&mut self, event: SdlEvent, state: &mut S) {
        for pushrod_event in self.route(event) {
            self.fire(&pushrod_event, state);
        }
    }

    /// Routes a single `SDL2` event to the `Widget`s and returns the `Event`s they
    /// generated, without calling any callbacks.  Window-level events (quit, expose, resize) are
    /// handled here.
    fn route(&mut self, event: SdlEvent) -> Vec<Event> {
        match event {
            SdlEvent::Quit { .. } => {
                self.running = false;
                Vec::new()
            }

            SdlEvent::Window {
                win_event: WindowEvent::Exposed | WindowEvent::SizeChanged(..),
                ..
            } => {
                self.widget_cache.invalidate_all();
                Vec::new()
            }

            remaining_event => self.widget_cache.handle_event(remaining_event),
        }
    }

    /// Delivers a generated `Event` to the callbacks.
    fn fire(&mut self, event: &Event, state: &mut S) {
        let mut ui = Ui {
            widgets: &mut self.widget_cache,
            running: &mut self.running,
        };

        if let Event::Clicked { id, .. } = event
            && let Some(callbacks) = self.click_callbacks.get_mut(id)
        {
            for callback in callbacks.iter_mut() {
                callback(state, &mut ui);
            }
        }

        for callback in self.event_callbacks.iter_mut() {
            callback(state, &mut ui, event);
        }
    }

    /// Runs the application until the window is closed or a callback calls `shutdown`.
    ///
    /// Each frame, the loop processes waiting input events (routing them to `Widget`s and calling
    /// callbacks), repaints changed `Widget`s, presents the frame if anything changed, then sleeps for
    /// the rest of the frame time.
    ///
    /// # Arguments
    ///
    /// * `sdl` - The initialized `SDL2` context.
    /// * `window` - The window to draw into.
    /// * `state` - The application state, passed to every callback.
    ///
    /// # Returns
    ///
    /// The application state, after the last callback has run.
    ///
    /// # Panics
    ///
    /// Panics if `SDL2` cannot create a hardware-accelerated canvas for the window or an event pump.
    pub fn run(&mut self, sdl: Sdl, window: Window, mut state: S) -> S {
        // Initializes the canvas, creating a textured canvas against which GPU textures will be
        // used, specifying hardware acceleration.
        let mut canvas = Self::create_canvas(window);

        // Attaches to the `SDL` library event pump, against which all windowed events are
        // sent.  Also determines the amount of time to wait between frames.
        let mut event_pump = sdl.event_pump().unwrap();
        let frame_time = Duration::from_millis((1000.0 / self.frame_rate.max(1) as f64) as u64);

        self.widget_cache.invalidate_all();

        // This is the run loop.  It performs the following tasks in the following order:
        //
        // First, it pulls all of the events that have been generated by the OS, placed into the
        // event_pump variable, which is controlled by SDL2.
        //
        // Second, each event is dispatched: the WidgetCache routes it to the appropriate Widget,
        // and any Events the Widgets generate are delivered to the registered callbacks,
        // in the order in which they were generated.
        //
        // Third, any Widgets that are invalidated are repainted into their textures, and if
        // anything changed, every visible Widget is copied to the screen and the canvas is
        // presented.
        //
        // Afterward, if the loop was ahead of the frame time, it waits before repeating, making
        // sure the system keeps within the desired FPS of the drawing engine.
        //
        // If the user clicks close on the window, or a callback calls `shutdown`, the run loop
        // terminates and the application state is returned.
        loop {
            let start = Instant::now();

            for event in event_pump.poll_iter() {
                self.dispatch(event, &mut state);
            }

            if !self.running {
                break;
            }

            if self
                .widget_cache
                .draw_loop(&mut canvas, &mut self.font_cache)
            {
                canvas.present();
            }

            let elapsed = start.elapsed();

            if elapsed < frame_time {
                sleep(frame_time - elapsed);
            }
        }

        state
    }

    /// Creates the hardware-accelerated canvas that widget textures are drawn to, cleared to
    /// white.
    ///
    /// On macOS the OpenGL renderer is requested unless the `SDL_RENDER_DRIVER` environment
    /// variable is set: with the Metal and software renderers the whole window appears to move
    /// one pixel each time a click repaints a widget, and OpenGL does not.  Set
    /// `SDL_RENDER_DRIVER` to choose another renderer.
    fn create_canvas(window: Window) -> Canvas<Window> {
        #[cfg(target_os = "macos")]
        if std::env::var_os("SDL_RENDER_DRIVER").is_none() {
            sdl2::hint::set("SDL_RENDER_DRIVER", "opengl");
        }

        let mut canvas = window
            .into_canvas()
            .target_texture()
            .accelerated()
            .build()
            .unwrap();

        canvas.set_draw_color(SdlColor::RGBA(255, 255, 255, 255));
        canvas.clear();
        canvas.present();

        canvas
    }

    /// Starts an application-driven event loop, as an alternative to [`Engine::run`] and callbacks.
    ///
    /// Call [`Engine::next_event`] repeatedly to receive the events generated by the `Widget`s.
    ///
    /// # Arguments
    ///
    /// * `sdl` - The initialized `SDL2` context.
    /// * `window` - The window to draw into.
    ///
    /// # Returns
    ///
    /// The [`EventLoop`] to pass to [`Engine::next_event`].
    ///
    /// # Panics
    ///
    /// Panics if `SDL2` cannot create a hardware-accelerated canvas for the window or an event pump.
    ///
    /// # Examples
    ///
    /// ```rust,no_run
    /// # use pushrod::engine::Engine;
    /// # use pushrod::event::Event;
    /// # use pushrod::geometry::size;
    /// # let sdl = sdl2::init().unwrap();
    /// # let window = sdl.video().unwrap().window("app", 400, 200).build().unwrap();
    /// let mut engine: Engine = Engine::new(size(400, 200), 60);
    /// let mut events = engine.event_loop(&sdl, window);
    ///
    /// while let Some(event) = engine.next_event(&mut events) {
    ///     if let Event::Clicked { id, .. } = event {
    ///         println!("widget {} clicked", id);
    ///     }
    /// }
    /// ```
    pub fn event_loop(&mut self, sdl: &Sdl, window: Window) -> EventLoop {
        self.widget_cache.invalidate_all();

        EventLoop {
            canvas: Self::create_canvas(window),
            event_pump: sdl.event_pump().unwrap(),
            frame_time: Duration::from_millis((1000.0 / self.frame_rate.max(1) as f64) as u64),
            pending: VecDeque::new(),
        }
    }

    /// Returns the next event generated by the `Widget`s, waiting for input as needed.
    ///
    /// While waiting, the screen is kept up to date: invalidated `Widget`s are repainted and the
    /// frame is presented, so changes made to `Widget`s between calls appear immediately.  When nothing
    /// happens, the call blocks without using the CPU.  Callbacks registered with `on_click` and
    /// `on_event` are not called in this style; handle the returned events instead.
    ///
    /// # Arguments
    ///
    /// * `events` - The loop state returned by [`Engine::event_loop`].
    ///
    /// # Returns
    ///
    /// The next event, or `None` once the window has been closed or [`shutdown`](Engine::shutdown)
    /// has been called.
    pub fn next_event(&mut self, events: &mut EventLoop) -> Option<Event> {
        loop {
            if let Some(event) = events.pending.pop_front() {
                return Some(event);
            }

            if !self.running {
                return None;
            }

            if self
                .widget_cache
                .draw_loop(&mut events.canvas, &mut self.font_cache)
            {
                events.canvas.present();
            }

            // Wait for one event (at most one frame), then take whatever else is queued.
            let timeout = events.frame_time.as_millis().max(1) as u32;
            let mut sdl_events: Vec<SdlEvent> = events
                .event_pump
                .wait_event_timeout(timeout)
                .into_iter()
                .collect();

            sdl_events.extend(events.event_pump.poll_iter());

            for sdl_event in sdl_events {
                let generated = self.route(sdl_event);

                events.pending.extend(generated);
            }
        }
    }
}

/// The state of an application-driven event loop.
///
/// Created by [`Engine::event_loop`] and passed to [`Engine::next_event`].  It holds the window's
/// canvas, the `SDL2` event pump, the frame time, and events that have been generated but not yet
/// returned.
pub struct EventLoop {
    canvas: Canvas<Window>,
    event_pump: EventPump,
    frame_time: Duration,
    pending: VecDeque<Event>,
}
